// Browser-only component acceptance. The Rust and native WebView2 suites test the real backend.
import { chromium } from 'playwright';
import { createServer } from 'vite';
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createFixture } from './agents-fixture.mjs';
const root = path.resolve(import.meta.dirname, '..');
const artifacts = path.join(root, 'artifacts', 'agents-browser');
await mkdir(artifacts, { recursive: true });
const report = { success: false, checks: [], rendererErrors: [] };
const save = () => writeFile(path.join(artifacts, 'result.json'), JSON.stringify(report, null, 2) + '\n');
await save();
let browser, server;
const fixture = createFixture();
const { fullText } = fixture;
const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
try {
  server = await createServer({ root, configFile: path.join(root, 'vite.config.ts'), server: { port: 0, strictPort: false } });
  await server.listen();
  const address = server.httpServer.address();
  browser = await chromium.launch({ headless: true, ...(process.env.PI_DESKTOP_CHROMIUM ? { executablePath: process.env.PI_DESKTOP_CHROMIUM } : {}) });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, permissions: ['clipboard-read', 'clipboard-write'] });
  page.on('pageerror', error => report.rendererErrors.push(error.message));
  await page.exposeFunction('__agentBridge', fixture.agentTasks);
  await page.addInitScript(() => { window.pi = { agentTasks: data => window.__agentBridge(data || { action: 'list' }) }; });
  await page.goto(`http://127.0.0.1:${address.port}/tests/agents-harness.html`);
  const row = id => page.locator(`[data-task-id="task-${id}"]`);
  await row('00').waitFor();
  assert.equal(await page.locator('.agent-task-row').count(), 20);
  await page.getByLabel('下一页任务', { exact: true }).click(); await row('20').waitFor();
  await page.getByLabel('下一页任务', { exact: true }).click(); await row('40').waitFor();
  assert.equal(await page.locator('.agent-task-row').count(), 5);
  assert.equal(await page.getByLabel('下一页任务', { exact: true }).isDisabled(), true);
  await page.getByLabel('上一页任务', { exact: true }).click(); await row('20').waitFor();
  report.checks.push('任务跨页、末页和上一页');
  const search = page.getByLabel('搜索探子任务', { exact: true });
  await search.fill('slow'); await wait(60); await search.fill('记录 44'); await row('44').waitFor();
  assert.equal(await page.locator('.agent-task-row').count(), 1);
  await page.getByLabel('筛选探子状态').selectOption('attention'); await page.getByText('这里还没有匹配的任务。', { exact: true }).waitFor();
  await page.getByLabel('筛选探子状态').selectOption('all'); await row('44').waitFor();
  await search.fill(''); await row('00').waitFor();
  await page.getByLabel('当前工作区', { exact: true }).check();
  await page.waitForFunction(() => document.querySelector('.task-pagination')?.textContent.includes('23 项'));
  assert.equal(await row('01').count(), 0);
  await page.getByLabel('当前工作区', { exact: true }).uncheck();
  await page.getByLabel('每页任务数').selectOption('10'); await page.waitForFunction(() => document.querySelectorAll('.agent-task-row').length === 10);
  report.checks.push('搜索、组合筛选、页大小与过期筛选响应');
  await row('02').click(); await page.getByText('预览 2', { exact: true }).waitFor();
  await page.getByRole('button', { name: '查看完整结果', exact: true }).click();
  await page.getByRole('button', { name: '下一页结果', exact: true }).waitFor();
  let collected = await page.getByTestId('task-output').textContent();
  while (await page.getByRole('button', { name: '下一页结果', exact: true }).isEnabled()) {
    const offset = await page.locator('.task-output-pages').textContent();
    await page.getByRole('button', { name: '下一页结果', exact: true }).click();
    await page.waitForFunction(before => document.querySelector('.task-output-pages')?.textContent !== before && !document.querySelector('.task-output-pages [role="status"]'), offset);
    collected += await page.getByTestId('task-output').textContent();
  }
  assert.equal(collected, fullText);
  await page.getByRole('button', { name: '复制当前页', exact: true }).click();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), await page.getByTestId('task-output').textContent());
  await page.getByRole('button', { name: '引用当前页到消息', exact: true }).click();
  assert.match(await page.evaluate(() => window.__lastReference), /完整结果第 4 页/);
  await page.getByRole('button', { name: '上一页结果', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('.task-output-pages')?.textContent.startsWith('第 3 页'));
  await page.screenshot({ path: path.join(artifacts, 'full-result.png') });
  report.checks.push('超过 128 KiB 的完整中文结果、前后翻页、当前页复制和引用');
  await page.getByRole('button', { name: '返回结果预览', exact: true }).click();
  fixture.setOutputDelay(300);
  await page.getByRole('button', { name: '查看完整结果', exact: true }).click(); await row('03').click();
  await page.getByText('预览 3', { exact: true }).waitFor(); await wait(400);
  assert.equal(await page.getByTestId('task-output').textContent(), '预览 3'); fixture.setOutputDelay(0);
  await row('00').click(); await page.getByRole('button', { name: '取消任务', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '归档任务', exact: true }).count(), 0);
  await row('01').click(); await page.getByRole('button', { name: '继续会话', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '归档任务', exact: true }).count(), 0);
  report.checks.push('切换任务丢弃过期结果、活跃与中断任务无归档入口');
  await search.fill('记录 02'); await row('02').click();
  await page.getByRole('button', { name: '归档任务', exact: true }).click();
  await page.getByText('这里还没有匹配的任务。', { exact: true }).waitFor();
  await page.getByLabel('筛选归档任务').selectOption('archived'); await row('02').waitFor();
  await page.getByRole('button', { name: '恢复归档任务', exact: true }).click();
  await page.getByText('这里还没有匹配的任务。', { exact: true }).waitFor();
  await page.getByLabel('筛选归档任务').selectOption('current'); await row('02').waitFor();
  await page.screenshot({ path: path.join(artifacts, 'search-and-restore.png') });
  report.checks.push('归档、归档筛选和原任务恢复');
  assert.deepEqual(report.rendererErrors, []);
  report.success = true;
} catch (error) { report.error = error.stack; process.exitCode = 1; }
finally { await browser?.close(); await server?.close(); await save(); }
console.log(JSON.stringify(report, null, 2));
